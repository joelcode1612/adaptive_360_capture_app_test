-- =============================================================================
-- SiteWise SQL harness · the pre-migration ("legacy") state
-- =============================================================================
--
-- Recreates the schema as it is assumed to be BEFORE the SiteWise migrations,
-- so that the migrations are tested against a realistic starting point rather
-- than against an empty database they themselves shaped.
--
-- Deliberately included, because each one is a claim the migrations make:
--   * a three-value role CHECK, so the migration's drop-by-lookup has something
--     to find and replace;
--   * a NULL role, so the migration's "a NULL role is ambiguous" repair runs;
--   * a non-internal trigger and an inbound foreign key on `public.users`, so
--     the migration's "this changes nothing else" claim is testable;
--   * `pano_jobs` WITHOUT `property_id`, plus one legacy row holding a device
--     path, so the NOT VALID path CHECK can be shown to constrain new writes
--     while leaving history alone.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. public.users — three roles, nullable, default entrepreneur
-- -----------------------------------------------------------------------------
create table if not exists public.users (
  user_id    uuid primary key default gen_random_uuid(),
  email      text unique,
  full_name  text,
  role       text default 'entrepreneur',
  status     text not null default 'active',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint users_role_check check (role in ('entrepreneur', 'agent', 'admin')),
  constraint users_status_check check (status in ('active', 'suspended', 'deleted'))
);

-- A non-internal trigger the migration must not disturb.
create or replace function public.users_touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists users_touch_updated_at on public.users;
create trigger users_touch_updated_at
  before update on public.users
  for each row
  execute function public.users_touch_updated_at();

-- -----------------------------------------------------------------------------
-- 2. public.property — bigint key, uuid owner
-- -----------------------------------------------------------------------------
create table if not exists public.property (
  property_id   bigint primary key generated by default as identity,
  title         text,
  owner_id      uuid references public.users (user_id) on delete set null,
  published     boolean not null default false,
  created_at    timestamptz not null default now()
);

-- -----------------------------------------------------------------------------
-- 3. public.agent — the verified assignment row
-- -----------------------------------------------------------------------------
create table if not exists public.agent (
  agent_id    bigint primary key generated by default as identity,
  property_id bigint not null references public.property (property_id) on delete cascade,
  user_id     uuid not null references public.users (user_id) on delete cascade,
  created_at  timestamptz not null default now(),
  unique (property_id, user_id)
);

-- -----------------------------------------------------------------------------
-- 4. public.pano_jobs — the ERD's job table, before `property_id` is added
-- -----------------------------------------------------------------------------
create table if not exists public.pano_jobs (
  id            text primary key,
  session_id    text not null,
  owner         uuid references public.users (user_id) on delete cascade,
  status        text not null default 'queued',
  frames        jsonb,
  panorama_path text,
  error         text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint pano_jobs_status_check
    check (status in ('queued', 'processing', 'done', 'error'))
);

-- -----------------------------------------------------------------------------
-- 5. An inbound foreign key, so "FKs still reference public.users" is provable
-- -----------------------------------------------------------------------------
create table if not exists public.user_profile (
  user_id  uuid primary key references public.users (user_id) on delete cascade,
  headline text
);

grant select, insert, update, delete on public.users to authenticated;
grant select, insert, update, delete on public.property to authenticated;
grant select, insert, update, delete on public.agent to authenticated;
grant select, insert, update, delete on public.pano_jobs to authenticated;
grant select, insert, update, delete on public.user_profile to authenticated;
grant usage, select on all sequences in schema public to authenticated;

